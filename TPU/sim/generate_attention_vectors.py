"""Generate Verilog test vectors directly from the Python golden model."""

from __future__ import annotations

import argparse
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from toy_attention import pack_rows, reference_case, stress_case


def int16_le(values) -> list[int]:
    result = []
    for value in values:
        encoded = int(value) & 0xFFFF
        result.extend((encoded & 0xFF, (encoded >> 8) & 0xFF))
    return result


def bytes_for_case(trace) -> dict[str, list[int]]:
    return {
        "stimulus": [
            *pack_rows(trace.x),
            *pack_rows(trace.wq),
            *pack_rows(trace.wk),
            *pack_rows(trace.wv),
        ],
        "result": pack_rows(trace.output),
        "q": pack_rows(trace.q),
        "k": pack_rows(trace.k),
        "v": pack_rows(trace.v),
        "scores": int16_le(trace.scores[-1]),
        "weights": [int(value) for value in trace.weights[-1]],
        "denominator": [int(trace.denominators[-1])],
        "numerators": int16_le(trace.numerators[-1]),
        "reciprocal": [int(trace.reciprocals_q08[-1])],
    }


def render_array(name: str, cases: list[dict[str, list[int]]], key: str) -> list[str]:
    width = len(cases[0][key])
    lines = [f"reg [7:0] {name} [0:(NUM_CASES*{width})-1];"]
    for case_index, case in enumerate(cases):
        if len(case[key]) != width:
            raise ValueError(f"all {key} vectors must have the same length")
        for byte_index, value in enumerate(case[key]):
            index = case_index * width + byte_index
            lines.append(f"        {name}[{index}] = 8'h{value:02x};")
    return lines


def generate(output: Path) -> None:
    cases = [bytes_for_case(reference_case()), bytes_for_case(stress_case())]
    arrays = [
        ("golden_stimulus", "stimulus"),
        ("golden_result", "result"),
        ("golden_q", "q"),
        ("golden_k", "k"),
        ("golden_v", "v"),
        ("golden_scores", "scores"),
        ("golden_weights", "weights"),
        ("golden_denominator", "denominator"),
        ("golden_numerators", "numerators"),
        ("golden_reciprocal", "reciprocal"),
    ]

    declarations = []
    assignments = []
    for name, key in arrays:
        rendered = render_array(name, cases, key)
        declarations.append(rendered[0])
        assignments.extend(rendered[1:])

    text = "\n".join(
        [
            "// Generated by sim/generate_attention_vectors.py. Do not edit.",
            f"localparam integer NUM_CASES = {len(cases)};",
            *declarations,
            "",
            "initial begin : initialize_golden_vectors",
            *assignments,
            "end",
            "",
        ]
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text, encoding="ascii")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    generate(args.output)


if __name__ == "__main__":
    main()
